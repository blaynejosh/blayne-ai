/**
 * Splits design/Home.svg into React components.
 *
 *   npm run extract:hero
 *
 * The hero is a Figma export whose type is outlined, so it cannot be styled,
 * selected, translated or read by a screen reader. This script keeps the
 * decorative artwork as vector (pixel-faithful) and drops the chrome that
 * Hero rebuilds as real HTML: the five pills, the four category labels and
 * the centre wordmark.
 *
 * Line ranges refer to the source export. If Home.svg is re-exported from
 * Figma they must be re-checked — run with --audit to print what each range
 * currently covers.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(root, 'src', 'components');

const read = (file) =>
  fs.readFileSync(path.join(root, 'design', file), 'utf8').split(/\r?\n/);

const lines = read('Home.svg');
const seg = (a, b) => lines.slice(a - 1, b).join('\n'); // 1-indexed, inclusive

const mapLines = read('Features page.svg');
const mapSeg = (a, b) => mapLines.slice(a - 1, b).join('\n');

const chatLines = read('AI chat area - Features.svg');
const chatSeg = (a, b) => chatLines.slice(a - 1, b).join('\n');

/** Layers of the export, by line range. */
const LAYERS = {
  plate: [3, 3], //          flat #3A405A background
  grid: [4, 567], //         dot + rule grid at 8% opacity
  glow: [568, 581], //       the BLAYNE brain emblem, gaussian-blurred
  gem: [582, 594], //        centre gem mark + its four tick marks
  dendrites: [600, 705], //  orange sparks, connectors, blue/orange nodes
  rule: [721, 721], //       hairline under the header
  mark: [722, 734], //       header gem mark
  defs: [736, lines.length],
};

/** Dropped — rebuilt as real HTML in Hero.jsx. */
const REBUILT_AS_HTML = {
  wordmark: [595, 595],
  categoryLabels: [596, 599],
  pills: [706, 720],
};

/**
 * Features page.svg — the template for every Product Map section.
 * Only the ambient layers and the node cluster are kept: the title and the
 * 20 item labels become HTML, the header chrome belongs to the hero, and the
 * fan of curves is regenerated per item count by src/lib/fan.js.
 */
const MAP_LAYERS = {
  plate: [3, 3],
  grid: [4, 567],
  glow: [568, 581],
  clusterLines: [603, 627], // rotated rects joining the nodes
  clusterNodes: [628, 674], // filled dots + their outer rings
  defs: [712, 721],
};

const MAP_DROPPED = {
  title: [582, 582],
  itemLabels: [583, 602],
  headerChrome: [675, 691], // search pill, hairline rule, gem mark
  fanCurves: [692, 710],
};

/**
 * AI chat area - Features.svg — the template for the four chat pages.
 * Only the wash is kept; the nav, sidebar, panel and composer are all real
 * HTML because every one of them is interactive.
 */
const CHAT_LAYERS = {
  plate: [3, 3],
  grid: [4, 567],
  glow: [568, 581],
  glowFilter: [634, 638],
  clip: [649, 651],
};

const CHAT_DROPPED = {
  sidebarLabels: [582, 601],
  rule: [602, 602],
  mark: [603, 615],
  panel: [616, 617], // surface + composer field
  panelText: [618, 619],
  icons: [620, 624], // plus, hamburger
  navTabs: [625, 628],
  activeUnderline: [629, 631],
};

if (process.argv.includes('--audit')) {
  console.log('--- AI chat area - Features.svg ---');
  for (const [name, [a, b]] of Object.entries({ ...CHAT_LAYERS, ...CHAT_DROPPED })) {
    console.log(`${name.padEnd(16)} ${a}-${b}  ${chatSeg(a, a).trim().slice(0, 66)}`);
  }
  console.log('\n--- Home.svg ---');
  for (const [name, [a, b]] of Object.entries({ ...LAYERS, ...REBUILT_AS_HTML })) {
    console.log(`${name.padEnd(16)} ${a}-${b}  ${seg(a, a).trim().slice(0, 66)}`);
  }
  console.log('\n--- Features page.svg ---');
  for (const [name, [a, b]] of Object.entries({ ...MAP_LAYERS, ...MAP_DROPPED })) {
    console.log(`${name.padEnd(16)} ${a}-${b}  ${mapSeg(a, a).trim().slice(0, 66)}`);
  }
  process.exit(0);
}

/** SVG attributes -> React props. Leaves data-/aria- and path data alone. */
const toJsx = (s) =>
  s
    .replace(/([a-z]+)-([a-z])/g, (m, a, b) =>
      a === 'data' || a === 'aria' ? m : a + b.toUpperCase(),
    )
    .replace(/\bclass=/g, 'className=');

const indent = (s, n) =>
  s
    .split('\n')
    .map((l) => ' '.repeat(n) + l)
    .join('\n');

const banner = (what) =>
  `// AUTO-GENERATED by scripts/extract-hero-svg.mjs from design/Home.svg.\n` +
  `// ${what}\n` +
  `// Do not edit by hand — re-run \`npm run extract:hero\` instead.\n`;

const body = ['plate', 'grid', 'glow', 'gem', 'dendrites', 'rule']
  .map((k) => seg(...LAYERS[k]))
  .join('\n');

const defs = seg(...LAYERS.defs).replace(/<\/svg>\s*$/, '').trimEnd();

fs.mkdirSync(OUT, { recursive: true });

fs.writeFileSync(
  path.join(OUT, 'HeroBackdrop.jsx'),
  `${banner('Decorative layers only — chrome is rebuilt as HTML in Hero.jsx.')}
export default function HeroBackdrop({ className = '', preserveAspectRatio = 'xMidYMid meet' }) {
  return (
    <svg
      className={className}
      viewBox="0 0 1440 1024"
      fill="none"
      xmlns="http://www.w3.org/2000/svg"
      preserveAspectRatio={preserveAspectRatio}
      aria-hidden="true"
      focusable="false"
    >
      <g clipPath="url(#clip0_4_669)">
${indent(toJsx(body), 8)}
      </g>
${indent(toJsx(defs), 6)}
    </svg>
  );
}
`,
);

fs.writeFileSync(
  path.join(OUT, 'BlayneMark.jsx'),
  `${banner('The BLAYNE gem mark, lifted from the header of the export.')}
export default function BlayneMark({ className = '' }) {
  return (
    <svg
      className={className}
      viewBox="215 40 47 50"
      fill="none"
      xmlns="http://www.w3.org/2000/svg"
      aria-hidden="true"
      focusable="false"
    >
${indent(toJsx(seg(...LAYERS.mark)), 6)}
    </svg>
  );
}
`,
);

const mapBody = ['plate', 'grid', 'glow', 'clusterLines', 'clusterNodes']
  .map((k) => mapSeg(...MAP_LAYERS[k]))
  .join('\n');

fs.writeFileSync(
  path.join(OUT, 'MapBackdrop.jsx'),
  `${banner('Ambient layers + node cluster shared by every Product Map section.')}
export default function MapBackdrop({ className = '', preserveAspectRatio = 'xMidYMid meet' }) {
  return (
    <svg
      className={className}
      viewBox="0 0 1440 1024"
      fill="none"
      xmlns="http://www.w3.org/2000/svg"
      preserveAspectRatio={preserveAspectRatio}
      aria-hidden="true"
      focusable="false"
    >
      <g clipPath="url(#clip0_21_956)">
${indent(toJsx(mapBody), 8)}
      </g>
${indent(toJsx(mapSeg(...MAP_LAYERS.defs)), 6)}
    </svg>
  );
}
`,
);

const chatBody = ['plate', 'grid', 'glow']
  .map((k) => chatSeg(...CHAT_LAYERS[k]))
  .join('\n');

fs.writeFileSync(
  path.join(OUT, 'ChatBackdrop.jsx'),
  `${banner('Grid + brand glow behind the chat surface.')}
export default function ChatBackdrop({ className = '', preserveAspectRatio = 'xMidYMid meet' }) {
  return (
    <svg
      className={className}
      viewBox="0 0 1440 1024"
      fill="none"
      xmlns="http://www.w3.org/2000/svg"
      preserveAspectRatio={preserveAspectRatio}
      aria-hidden="true"
      focusable="false"
    >
      <g clipPath="url(#clip0_24_1856)">
${indent(toJsx(chatBody), 8)}
      </g>
      <defs>
${indent(toJsx(chatSeg(...CHAT_LAYERS.glowFilter)), 8)}
${indent(toJsx(chatSeg(...CHAT_LAYERS.clip)), 8)}
      </defs>
    </svg>
  );
}
`,
);

console.log('wrote HeroBackdrop.jsx + BlayneMark.jsx + MapBackdrop.jsx + ChatBackdrop.jsx');
